                                                .map((e) => e.flagType)
                                                .whereType<FlagModel>(),
                                          ];
                                          return AddFlagAndAttachment(
                                            key: ValueKey(model),
                                            model: model,
                                            onDelete: i == 0
                                                ? null
                                                : () {
                                                    setState(
                                                      () => attachments
                                                          .removeAt(i),
                                                    );
                                                  },
                                          );
                                        },
                                      ),
                                      const SizedBox(height: 12),
                                      Align(
                                        alignment: Alignment.centerRight,
                                        child: AppOutlineButton(
                                          onPressed: () {
                                            setState(() {
                                              attachments.add(
                                                FlagAndAttachmentModel(),
                                              );
                                            });
                                          },
